// ── Types ──────────────────────────────────────────────────────────────────
interface InflectionRow {
    label: string;
    form: string;
    hasPage: boolean;
    entryId?: string;
    marker?: 'plain' | 'theoretical' | 'auto_generated'; // these + labels appear at black/55
    secondary?: {
        form: string;
        hasPage: boolean;
        entryId?: string;
        marker?: 'plain' | 'theoretical' | 'auto_generated';
    };
}

interface SearchResult {
    id: string;
    headword: string;
    root: string;
    rootSlug: string;
    rootHref: string;
    gender?: string;    // shown as Egyptian Blue below root
    pos: string;
    definitions: string[];
    inflections: InflectionRow[];
    entry: any;
}

type SearchSuggestion = Pick<SearchResult, 'id' | 'headword' | 'pos' | 'definitions'>;

